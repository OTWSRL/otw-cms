import { mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { generate, parseConfig, renderPluginsModule } from '../src/generate.ts'

describe('parseConfig', () => {
  it('accepts scoped and unscoped package names', () => {
    expect(parseConfig({ plugins: ['@cms/plugin-commerce', 'cms-plugin-lms'] })).toEqual({
      plugins: ['@cms/plugin-commerce', 'cms-plugin-lms'],
    })
  })

  it.each([
    [{}, 'must contain a "plugins" array'],
    [null, 'must contain a "plugins" array'],
    [{ plugins: 'commerce' }, 'must contain a "plugins" array'],
    [{ plugins: [42] }, 'Invalid plugin package name: 42'],
    [{ plugins: ['Upper'] }, 'Invalid plugin package name'],
    [{ plugins: ["x'; process.exit(1); '"] }, 'Invalid plugin package name'],
    [{ plugins: ['../../etc'] }, 'Invalid plugin package name'],
    [{ plugins: ['a', 'a'] }, 'listed twice'],
  ])('rejects %j', (raw, message) => {
    expect(() => parseConfig(raw)).toThrow(message)
  })
})

describe('renderPluginsModule', () => {
  it('statically imports every plugin in config order', () => {
    expect(
      renderPluginsModule({ plugins: ['@cms/plugin-commerce', '@cms/plugin-commerce-stripe'] }),
    ).toBe(`// Generated by \`cms generate\` from cms.config.json. Do not edit.
import type { PluginDefinition } from '@cms/sdk'
import plugin0 from "@cms/plugin-commerce"
import plugin1 from "@cms/plugin-commerce-stripe"

export const installedPlugins: readonly PluginDefinition[] = [plugin0, plugin1]
`)
  })

  it('renders an empty list', () => {
    expect(renderPluginsModule({ plugins: [] })).toContain('= []')
  })
})

describe('generate', () => {
  let dir: string

  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), 'cms-cli-'))
  })

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true })
  })

  it('writes the module, then skips writing when nothing changed', async () => {
    const config = join(dir, 'cms.config.json')
    const out = join(dir, 'src/cms/plugins.generated.ts')
    await writeFile(config, JSON.stringify({ plugins: ['@cms/plugin-commerce'] }))

    expect(await generate({ config, out })).toEqual({ changed: true })
    expect(await readFile(out, 'utf8')).toContain('import plugin0 from "@cms/plugin-commerce"')
    const firstWrite = (await stat(out)).mtimeMs

    expect(await generate({ config, out })).toEqual({ changed: false })
    expect((await stat(out)).mtimeMs).toBe(firstWrite)
  })

  it('fails on invalid JSON without touching the output', async () => {
    const config = join(dir, 'cms.config.json')
    const out = join(dir, 'plugins.generated.ts')
    await writeFile(config, '{ plugins: ')
    await expect(generate({ config, out })).rejects.toThrow(SyntaxError)
    await expect(stat(out)).rejects.toThrow('ENOENT')
  })
})
